function normalizeStationKey(name) {
  return String(name || '')
    .toUpperCase()
    .replace(/[.]/g, '')
    .replace(/\bJUNCTION\b/g, 'JN')
    .replace(/\s+/g, ' ')
    .trim();
}

window.COACH_stationsByName = function stationsByName(master) {
  const out = {};
  for (const s of Object.values(master || {})) {
    const entry = {
      code: s.code,
      en: s.en || s.name || s.code,
      te: s.te || null,
      hi: s.hi || null
    };
    const keys = new Set([
      normalizeStationKey(entry.en),
      ...(s.aliases || []).map(normalizeStationKey)
    ]);
    for (const key of keys) {
      if (key) out[key] = entry;
    }
  }
  return out;
};

window.COACH_translateStatus = function translateStatus(status, lang) {
  const dict = window.COACH_I18N[lang] || window.COACH_I18N.en;
  const s = String(status || '');
  if (!s || s === '—') return s;
  if (/^on time$/i.test(s)) return dict.onTime;
  if (/^arrived$/i.test(s)) return dict.arrived;
  if (/^departed$/i.test(s)) return dict.departed;
  if (/cancel/i.test(s)) return dict.cancelled;
  if (/divert/i.test(s)) return dict.diverted;
  const late = s.match(/late by\s+(\d+)\s*mins?/i);
  if (late) return dict.lateBy.replace('{n}', late[1]);
  return s;
};

window.COACH_localizeStationName = function localizeStationName(name, lang, map) {
  if (!name) return '—';
  if (!lang || lang === 'en') return name;
  const key = normalizeStationKey(name);
  const candidates = [
    key,
    key.replace(/\s+JN$/, ''),
    key.replace(/\s+CITY$/, ''),
    key.replace(/\s+RD$/, ' ROAD'),
    key.replace(/\s+ROAD$/, ' RD'),
    `${key.replace(/\s+JN$/, '')} JN`
  ];
  let row = null;
  for (const c of candidates) {
    if (map && map[c]) {
      row = map[c];
      break;
    }
  }
  if (!row && map) {
    const hit = Object.keys(map).find((k) => k.startsWith(key) || key.startsWith(k));
    if (hit) row = map[hit];
  }
  if (row && row[lang]) return row[lang];
  return name;
};

window.COACH_localizeTrainName = function localizeTrainName(name, lang) {
  if (!name) return '—';
  if (!lang || lang === 'en') return name;
  const upper = String(name).toUpperCase().replace(/\s+/g, ' ').trim();
  const named = NAMED_TRAINS[upper];
  if (named && named[lang]) return named[lang];
  const tokens = TRAIN_NAME_TOKENS[lang] || {};
  return String(name)
    .split(/(\s+|[-/])/)
    .map((part) => tokens[part.toUpperCase()] || part)
    .join('');
};
